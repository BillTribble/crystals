  const r = () => Math.random();
  const range = (lo, hi, step = 0.01) => {
    const v = lo + r() * (hi - lo);
    return Number((Math.round(v / step) * step).toFixed(4));
  };
  const pick = (arr) => arr[Math.floor(r() * arr.length)];

  const habit = pick(HABITS);
  const hue = r();
  const hue2 = (hue + 0.18 + 0.48 * r()) % 1;
  const stoneSat = range(0.78, 0.98);
  const stoneColour = okhslToHex(hue, stoneSat, range(0.45, 0.65));
  const coreColour = okhslToHex(hue2, range(0.76, 0.98), range(0.48, 0.68));
